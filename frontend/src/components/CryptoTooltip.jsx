/**
 * Interactive Crypto Tooltip & Badge Component
 * Hover or tap to reveal cryptographic rationale & security properties.
 */
export default function CryptoTooltip({ term, customTitle, customDescription, children, className = '' }) {
  const [visible, setVisible] = useState(false);
  const def = CRYPTO_DEFINITIONS[term] || {};
  const IconComponent = def.icon || Info;
  const timeoutRef = useRef(null);

  const show = () => {
    if (timeoutRef.current) clearTimeout(timeoutRef.current);
    setVisible(true);
  };

  const hide = () => {
    timeoutRef.current = setTimeout(() => {
      setVisible(false);
    }, 150);
  };

  return (
    <span
      className={`relative inline-flex items-center cursor-help ${className}`}
      onMouseEnter={show}
      onMouseLeave={hide}
      onClick={() => setVisible(!visible)}
    >
      {children}

      {visible && (
        <span
          className="absolute bottom-full left-1/2 -translate-x-1/2 mb-2 w-72 sm:w-80 p-3 bg-slate-900/95 backdrop-blur-md text-slate-200 border border-slate-700/80 rounded-xl shadow-2xl z-50 pointer-events-none text-left animate-in fade-in zoom-in-95 duration-150"
          style={{ minWidth: '260px' }}
        >
          <span className="flex items-center gap-2 mb-1.5 pb-1.5 border-b border-slate-800">
            <span className="w-5 h-5 rounded bg-emerald-500/20 border border-emerald-500/30 flex items-center justify-center text-emerald-400 flex-shrink-0">
              <IconComponent className="w-3 h-3" />
            </span>
            <span className="flex-1">
              <span className="text-[11px] font-bold text-white block leading-tight">
                {customTitle || def.title || term}
              </span>
              <span className="text-[9px] font-mono text-emerald-400 uppercase tracking-wider block">
                {def.category || 'Security Primitive'}
              </span>
            </span>
          </span>

          <span className="text-[11px] text-slate-300 block leading-relaxed mb-1">
            {customDescription || def.summary}
          </span>

          {def.details && (
            <span className="text-[10px] text-slate-400 font-sans block leading-normal pt-1 border-t border-slate-800/80">
              💡 {def.details}
            </span>
          )}

          {/* Tooltip Arrow */}
          <span className="absolute top-full left-1/2 -translate-x-1/2 -mt-1 border-4 border-transparent border-t-slate-800 pointer-events-none" />
        </span>
      )}
    </span>
  );
}
